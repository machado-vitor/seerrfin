    function detectLocale() {
        try {
            // 1. Jellyfin user display language, when the web client already resolved it.
            const userSettings = window.ApiClient && typeof ApiClient.getCurrentUserId === 'function'
                ? window.appStorage || null
                : null;
            void userSettings;

            const htmlLang = document.documentElement && document.documentElement.lang;
            if (htmlLang) return htmlLang;

            const stored = window.localStorage && window.localStorage.getItem('langpref-' + (window.ApiClient && ApiClient.getCurrentUserId ? ApiClient.getCurrentUserId() : ''));
            if (stored) return stored;
        } catch (error) {
            // ignore, fall through to navigator language
        }

        try {
            if (navigator.languages && navigator.languages.length) return navigator.languages[0];
            if (navigator.language) return navigator.language;
        } catch (error) {
            // ignore
        }

        return 'en';
    }

    function resolveDictionary(locale) {
        const normalized = String(locale || 'en').replace('_', '-');

        if (DICTIONARIES[normalized]) return DICTIONARIES[normalized];

        // pt, pt-PT, pt-BR all fall back to our single Portuguese dictionary.
        if (/^pt/i.test(normalized)) return DICTIONARIES['pt-BR'];

        const base = normalized.split('-')[0];
        const match = Object.keys(DICTIONARIES).find(function (key) { return key.split('-')[0].toLowerCase() === base.toLowerCase(); });

        return match ? DICTIONARIES[match] : DICTIONARIES.en;
    }

    function interpolate(template, params) {
        if (!params) return template;

        return template.replace(/\{\{\s*([\w]+)\s*\}\}/g, function (match, key) {
            return Object.prototype.hasOwnProperty.call(params, key) ? String(params[key]) : match;
        });
    }

    let currentLocale = detectLocale();
    let currentDictionary = resolveDictionary(currentLocale);

    function t(key, params) {
        let template = currentDictionary[key];

        if (template === undefined) template = DICTIONARIES.en[key];
        if (template === undefined) return key;

        // Plural helper: pass { count } and keys suffixed _one / _other.
        if (params && typeof params.count === 'number') {
            const suffix = params.count === 1 ? '_one' : '_other';
            const pluralKey = key + suffix;
            const pluralTemplate = currentDictionary[pluralKey] || DICTIONARIES.en[pluralKey];

            if (pluralTemplate !== undefined) template = pluralTemplate;
        }

        return interpolate(template, params);
    }

