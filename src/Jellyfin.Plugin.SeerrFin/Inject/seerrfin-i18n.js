    // Translates a raw English media/request status label (as returned by the
    // SeerrFin backend, e.g. "Partially Available") into the active locale.
    // Falls back to the raw label unchanged if it isn't a recognized status,
    // so unrelated free-form text is never mangled.
    function tMediaStatusLabel(rawLabel) {
        const key = MEDIA_STATUS_LABEL_KEYS[String(rawLabel || '').toLowerCase()];

        return key ? t(key) : rawLabel;
    }

    window.seerrFinI18n = {
        t: t,
        tMediaStatusLabel: tMediaStatusLabel,
        locale: currentLocale,
        setLocale: function (locale) {
            currentLocale = locale;
            currentDictionary = resolveDictionary(locale);
        }
    };
